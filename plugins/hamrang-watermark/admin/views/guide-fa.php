		<h2 id="h-restore">۸. نسخه‌ی اصلی و بازگردانی</h2>
		<p>وقتی «نگه‌داشتن نسخه‌ی اصلی» روشن است، قبل از اولین پردازش هر تصویر، یک کپی دست‌نخورده کنار آن با نام <code>نام-فایل-hamrang-orig.پسوند</code> ذخیره می‌شود و مسیرش در رکورد همان پیوست می‌ماند. بازگردانی یعنی همین فایل روی تصویر فعلی برمی‌گردد، بندانگشتی‌ها از نو ساخته می‌شوند و کپی اضافی حذف می‌شود. اگر پیوستی را از کتابخانه حذف کنید، کپی اصلی‌اش هم همراهش پاک می‌شود تا فایل یتیم نماند.</p>
		<p>چند نکته:</p>
		<ul>
			<li>تصاویری که با گزینه‌ی «نگه‌داشتن نسخه‌ی اصلی» <em>خاموش</em> واترمارک شده‌اند قابل بازگردانی نیستند و برای اعمال دوباره فقط با «اعمال دوباره» (روی واترمارک قبلی) پردازش می‌شوند.</li>
			<li>اگر تصویری را با ویرایشگر تصویر وردپرس (برش/چرخش) تغییر دهید، وردپرس فایل جدیدی می‌سازد؛ رکورد هم‌رنگ به فایل قبلی اشاره می‌کند. در این حالت آن تصویر را دوباره واترمارک کنید.</li>
			<li>برای تصاویر خیلی بزرگ که وردپرس خودش نسخه‌ی <code>-scaled</code> می‌سازد، هم‌رنگ همان نسخه‌ی scaled (که در سایت نمایش داده می‌شود) را پردازش می‌کند و فایل خامِ اولیه را دست نمی‌زند.</li>
		</ul>

		<h2 id="h-change">۹. تغییر لوگو یا ظاهر بعد از مدتی</h2>
		<p>هم‌رنگ برای هر ترکیب «لوگو + تنظیمات ظاهری» یک مُهر کوتاه می‌سازد و آن را روی هر تصویر پردازش‌شده ثبت می‌کند. وقتی لوگو یا ظاهر را عوض کنید، تصاویر قبلی در کتابخانه‌ی رسانه «واترمارک‌شده (تنظیمات قدیمی)» نشان داده می‌شوند. کافی است یک‌بار «پردازش دسته‌ای ← اعمال واترمارک» را اجرا کنید: تصاویر قدیمی به اصل برمی‌گردند و با ظاهر جدید ساخته می‌شوند؛ به‌روزها رد می‌شوند. تغییر گزینه‌های غیرظاهری (مثل حالت اعمال یا کیفیت JPEG) مهر را عوض نمی‌کند.</p>


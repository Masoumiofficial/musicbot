		<h2 id="h-faq">۱۱. پرسش‌های پرتکرار و رفع اشکال</h2>
		<p><strong>پیام «کتابخانه‌ی GD در دسترس نیست» می‌گیرم.</strong><br />افزونه‌ی <code>gd</code> در PHP هاست فعال نیست. در سی‌پنل/دایرکت‌ادمین از بخش انتخاب نسخه‌ی PHP آن را فعال کنید یا از پشتیبانی هاست بخواهید.</p>
		<p><strong>تصویر عوض شد ولی در سایت همان قبلی را می‌بینم.</strong><br />کش مرورگر، افزونه‌ی کش یا CDN. کش را پاک کنید یا صفحه را با Ctrl+F5 باز کنید. نام فایل‌ها عمداً عوض نمی‌شود تا لینک‌ها نشکنند.</p>
		<p><strong>«حافظه‌ی PHP کافی نیست».</strong><br />تصویر خیلی بزرگ است. <code>memory_limit</code> را به 256M برسانید (یا در <code>wp-config.php</code>: <code>define( 'WP_MAX_MEMORY_LIMIT', '256M' );</code>). هم‌رنگ پیش از پردازش، حافظه‌ی لازم را تخمین می‌زند و اگر کم باشد همان تصویر را رد می‌کند تا سایت قطع نشود.</p>
		<p><strong>لوگوی سفید روی بعضی کاورها خوب دیده نمی‌شود.</strong><br />در حالت پلاک، رنگ پلاک همیشه به بازه‌ای آورده می‌شود که لوگوی سفید خوانا باشد و روی پلاک‌های روشن خودکار کمی تیره‌تر می‌شود. اگر پلاک ندارید، یک «نسخه‌ی تیره» بدهید تا روی گوشه‌های روشن استفاده شود، یا سایه را پررنگ‌تر کنید.</p>
		<p><strong>چرا GIF و SVG پشتیبانی نمی‌شوند؟</strong><br />GIF متحرک با پردازش، حرکتش را از دست می‌داد و SVG اصلاً تصویر نقطه‌ای نیست. JPEG، PNG و WebP پوشش داده می‌شوند (و AVIF اگر PHP هاست پشتیبانی کند).</p>
		<p><strong>لوگوی خود سایت/آیکون سایت واترمارک خورد.</strong><br />در حالت «هر آپلود جدید» گزینه‌ی «PNG شفاف را رها کن» را روشن بگذارید و لوگوها را PNG شفاف آپلود کنید؛ آپلودهای سفارشی‌ساز (آیکون سایت، لوگوی سفارشی، پس‌زمینه) خودکار رد می‌شوند. اگر اتفاق افتاد، از کتابخانه‌ی رسانه «بازگردانی نسخه‌ی اصلی» را بزنید.</p>
		<p><strong>ربات یا اسکریپت من تصاویر را با REST API می‌فرستد؛ واترمارک می‌خورند؟</strong><br />بله. در حالت «تصاویر شاخص»، هر زمان <code>featured_media</code> یک نوشته ست شود پردازش انجام می‌شود؛ در حالت «هر آپلود جدید»، آپلود از طریق <code>/wp/v2/media</code> هم پوشش داده می‌شود.</p>
		<p><strong>چندسایتی (Multisite)؟</strong><br />هر سایت تنظیمات و پردازش مستقل خود را دارد؛ افزونه را می‌توانید روی هر سایت جداگانه فعال کنید.</p>
		<p><strong>اگر افزونه را حذف کنم چه می‌شود؟</strong><br />تصاویر همان‌طور که هستند می‌مانند. اگر گزینه‌ی «هنگام حذف افزونه داده‌ها پاک شود» روشن باشد، تنظیمات، رکوردها و نسخه‌های اصلی ذخیره‌شده هم حذف می‌شوند. اگر تصاویر دست‌نخورده را می‌خواهید، قبل از حذف، «بازگردانی نسخه‌ی اصلی» را روی «قبلاً واترمارک‌شده» اجرا کنید.</p>
		<p><strong>حریم خصوصی:</strong> هم‌رنگ هیچ داده‌ای به سرور دیگری نمی‌فرستد؛ تمام پردازش روی هاست خودتان انجام می‌شود.</p>
